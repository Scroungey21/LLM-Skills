#!/usr/bin/env python3
"""Generate the lineup: a function that places every authored structure side by side so the art director can judge them.

usage: gen_lineup.py --structures datapack/data/<ns>/structure --namespace <ns>
                     --out datapack/data/<ns>/function/lineup.mcfunction
                     [--manifest _project/lineup/lineup_manifest.json] [--gap 8] [--y 64] [--origin-x 0 --origin-z 0]

One row per district (first folder under --structures), buildings in a row spaced by their real footprint.
Run in a flat creative test world with the pack's datapack enabled: /function <ns>:lineup. Then take the screenshots
described in the style bible (fixed camera, fixed time, GUI hidden) and save them in _project/evidence/.
The function uses `forceload add` (max 256 chunks per command; rows are split) and `place template`
(Minecraft 1.19.3 and later). In 1.21+ data packs the function folder is `function/` (singular); on older versions
use `functions/`. This script was not run against a live game in the authoring environment: run it once and
fix the command syntax for your pinned version if the game rejects a line. Needs nbtlib.
"""
import argparse, json, pathlib, sys

try:
    import nbtlib
except ImportError:
    sys.exit("nbtlib is required: pip install nbtlib")


def read_size(path):
    nbt = nbtlib.load(path)
    root = nbt.get("") if "" in nbt else nbt
    s = root.get("size", [16, 16, 16])
    return int(s[0]), int(s[1]), int(s[2])


def chunk_ranges(x1, z1, x2, z2):
    """Split a block rectangle into chunk rectangles of at most 256 chunks."""
    cx1, cz1, cx2, cz2 = x1 >> 4, z1 >> 4, x2 >> 4, z2 >> 4
    step = 16  # 16 x 16 = 256 chunks
    out = []
    for ax in range(cx1, cx2 + 1, step):
        for az in range(cz1, cz2 + 1, step):
            out.append((ax * 16, az * 16, min(ax + step - 1, cx2) * 16 + 15, min(az + step - 1, cz2) * 16 + 15))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--structures", required=True)
    ap.add_argument("--namespace", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--manifest")
    ap.add_argument("--gap", type=int, default=8)
    ap.add_argument("--y", type=int, default=64)
    ap.add_argument("--origin-x", type=int, default=0)
    ap.add_argument("--origin-z", type=int, default=0)
    a = ap.parse_args()

    root = pathlib.Path(a.structures)
    files = sorted(root.rglob("*.nbt"))
    if not files:
        sys.exit(f"no .nbt files under {root}")
    rows = {}
    for f in files:
        rel = f.relative_to(root)
        rows.setdefault(rel.parts[0] if len(rel.parts) > 1 else "_root", []).append(rel)

    cmds, manifest = ["# generated by gen_lineup.py - do not edit by hand"], []
    z = a.origin_z
    for district, rels in sorted(rows.items()):
        x, depth = a.origin_x, 0
        placed = []
        for rel in rels:
            sx, sy, sz = read_size(root / rel)
            template = f"{a.namespace}:{rel.with_suffix('').as_posix()}"
            placed.append((template, x, sz))
            manifest.append({"template": template, "district": district, "x": x, "y": a.y, "z": z,
                             "size": [sx, sy, sz]})
            x += sx + a.gap
            depth = max(depth, sz)
        cmds.append(f"# row: {district} ({len(rels)} structures)")
        for (x1, z1, x2, z2) in chunk_ranges(a.origin_x, z, x - a.gap, z + depth):
            cmds.append(f"forceload add {x1} {z1} {x2} {z2}")
        for template, px, _ in placed:
            cmds.append(f"place template {template} {px} {a.y} {z}")
        z += depth + a.gap * 2

    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(cmds) + "\n")
    if a.manifest:
        m = pathlib.Path(a.manifest)
        m.parent.mkdir(parents=True, exist_ok=True)
        m.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {out} ({len(manifest)} structures in {len(rows)} rows)")


if __name__ == "__main__":
    main()
